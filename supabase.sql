create table if not exists public.ranking (
  id bigint generated by default as identity primary key,
  nome text,
  nome_usuario text,
  pontuacao integer not null check (pontuacao >= 0),
  criado_em timestamptz not null default now()
);

alter table public.ranking enable row level security;

grant select, insert on public.ranking to anon;

drop policy if exists "Permitir leitura pública do ranking" on public.ranking;
drop policy if exists "Permitir envio público de pontuação" on public.ranking;

create policy "Permitir leitura pública do ranking" on public.ranking
for select using (true);

create policy "Permitir envio público de pontuação" on public.ranking
for insert with check (true);

create index if not exists ranking_pontuacao_idx
on public.ranking (pontuacao desc);
